/**
 * 날짜 · 시각을 사람이 읽는 모양으로.
 *
 * 서버는 ISO 로 준다 — 2026-10-01T13:16:31.762754. 기계가 주고받기에는
 * 맞지만 화면에 그대로 찍으면 초와 마이크로초까지 보여서 읽을 수가 없다.
 *
 * <b>초는 거의 쓸모가 없다.</b> 창고 일은 분 단위로 이야기한다 — "두 시
 * 십육 분에 받았다" 지 "13시 16분 31.762초" 가 아니다. 그래서 분까지만
 * 자른다.
 *
 * 화면마다 같은 한 줄을 복사해 두고 있었다. 스물한 군데에 일곱 가지
 * 모양이 생겼고, 그중 하나는 자르는 순서가 달라 결과도 달랐다. 한 곳에
 * 둬야 같은 값이 같은 모양으로 보인다.
 */

/** 2026-10-01 13:16 */
export const stamp = (v, fallback = '-') =>
  v ? String(v).replace('T', ' ').slice(0, 16) : fallback

/** 2026-10-01 — 시각이 의미 없는 자리(납기 · 예정일)에 쓴다 */
export const day = (v, fallback = '-') => (v ? String(v).slice(0, 10) : fallback)

/** 13:16 — 같은 날 안에서 순서만 보면 되는 자리 */
export const clock = (v, fallback = '-') =>
  v ? String(v).replace('T', ' ').slice(11, 16) : fallback
