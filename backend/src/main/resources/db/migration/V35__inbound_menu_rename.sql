-- ============================================================================
-- 「입고예정」 메뉴를 「입고 관리」로 (INB-PG-001)
--
-- 이름이 하는 일보다 좁았다.
--
-- 이 화면은 예정만 보여 주지 않는다. 상태 필터가 기본 '전체' 라 입하 ·
-- 검수중 · 적치중 · 입고완료 · 취소까지 전부 나오고, 지난 입고를 되짚는
-- 자리도 여기뿐이다. 그런데 이름이 「입고예정」이라 <b>끝난 건을 여기서
-- 찾는다는 생각이 안 든다.</b>
--
-- 그리고 형제가 아니다.
--
--   입고 관리     목록 · 예정 등록 · 지난 건 조회     ← 전체를 보는 자리
--     입하 등록   차가 왔다고 찍는다                   ← 작업 자리
--     입고검수    센다
--     적치        놓는다
--
-- 아래 셋은 그 동작만 하는 화면이고, 맨 위는 성격이 다르다. 이름이 넷 다
-- 동작처럼 생기면 나란히 놓인 형제로 읽힌다.
--
--
-- 【 '관리' 는 이 시스템에서 이미 쓰는 말이다 】
--
--   주문 관리 · SKU 관리 · 빈 관리
--
-- 셋 다 등록과 조회를 한 화면에서 한다. 입고도 같은 규칙으로 둔다 —
-- 「입고 관리에서 예정을 등록한다」가 「주문 관리에서 주문을 등록한다」와
-- 다를 이유가 없다.
--
-- 화면 안의 '입고예정 등록' 같은 말은 그대로 둔다. 등록하는 것은 여전히
-- 예정이고, 그 말까지 바꾸면 무엇을 만드는지가 흐려진다.
-- ============================================================================
UPDATE tb_menu
   SET menu_name  = '입고 관리',
       updated_by = 'system',
       updated_at = CURRENT_TIMESTAMP
 WHERE menu_id = 'INB_PLANS';
