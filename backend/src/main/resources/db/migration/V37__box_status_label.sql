-- ============================================================================
-- 박스 상태 '닫음' 을 '포장 완료' 로 — 한 화면에서 같은 말이 두 뜻이었다
--
-- 패킹 화면에 '닫기' 가 셋인데 뜻이 둘이었다.
--
--   박스 [닫기]        테이프를 붙인다 — 업무 한 단계
--   패킹 창 [닫기]     화면을 닫는다
--   규격 모달 [닫기]   화면을 닫는다
--
-- 그리고 상태 배지가 '닫음' 으로 떴다. 같은 글자가 '창을 닫는다' 와 '상자를
-- 봉한다' 를 동시에 가리키니, 처음 보는 사람은 어느 쪽인지 알 수가 없다.
--
-- 정작 뜻은 코드 설명에 분명히 적혀 있었다 — '테이프를 붙였다. 더 못 넣는다.'
-- 그 말이 버튼에도 배지에도 없었을 뿐이다.
--
--
-- 【 왜 '포장 완료' 인가 】
--
-- <b>다음에 무엇이 되는지가 보인다.</b> 닫힌 박스에는 송장이 붙고, 송장이
-- 붙으면 다시 못 연다. '닫기' 는 되돌릴 수 있는 사소한 동작처럼 들리는데
-- 실제로는 그렇지 않다.
--
-- '봉인' 도 정확하지만 현장에서 쓰는 말이 아니고, '마감' 은 회계 쪽 말과
-- 겹친다.
--
-- 화면의 버튼도 함께 바꾼다 — [포장 완료] · [다시 담기]. 창을 닫는 '닫기'
-- 둘은 그대로 둔다. 그쪽은 어디서나 같은 뜻이라 헷갈릴 것이 없다.
--
-- OPEN('담는 중')은 건드리지 않는다. 이미 하는 일을 그대로 말하고 있다.
-- ============================================================================

UPDATE tb_code
   SET code_name   = '포장 완료',
       description = '테이프를 붙였다. 더 못 넣는다. 다음은 송장이다.',
       updated_by  = 'system',
       updated_at  = CURRENT_TIMESTAMP
 WHERE code_id = 'CLOSED'
   AND code_group_seq = (SELECT code_group_seq FROM tb_code_group
                          WHERE code_group_id = 'BOX_STATUS');

UPDATE tb_code_group
   SET description = '담는 중 · 포장 완료',
       updated_by  = 'system',
       updated_at  = CURRENT_TIMESTAMP
 WHERE code_group_id = 'BOX_STATUS';
