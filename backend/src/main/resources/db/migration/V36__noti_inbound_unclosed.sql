-- ============================================================================
-- 알림에 '입고완료 대기' 를 더한다 (COM-PG-015)
--
-- 적치를 다 해 놓고 입고완료를 안 누르면 아무 일도 안 일어난다.
--
--   물건은 빈에 있다        작업자가 놓았다
--   재고는 0 이다           입고완료에서만 재고가 된다 (INB-008)
--   정정도 못 한다          입고정정은 완료된 입고만 다룬다
--   알림도 없다             ← 여기
--
-- <b>어느 쪽으로도 못 가는 상태</b>인데 아무도 모른다. 그대로 며칠 지나면
-- 주문이 들어와 결품이 나고, 그 결품 알림을 보고서야 "입고완료를 안
-- 눌렀구나" 를 알게 된다. 재고가 창고에 있는데도.
--
--
-- 【 왜 자동으로 완료시키지 않나 】
--
-- 입고완료는 승인 행위다. 적치는 INB_PUTAWAY/C 로 작업자가 하고, 완료는
-- INB_APPROVE/A 로 센터 관리자가 한다 — 사람이 다르다. 자동으로 돌리면
-- 그 승인 단계가 사라진다.
--
-- 그래서 재촉만 한다. 누를지 말지는 여전히 사람이 정한다.
--
--
-- 【 누구에게 】
--
-- 센터 관리자다. 누를 수 있는 사람에게 가야 알림이 일을 한다 —
-- 작업자에게 띄우면 보고도 할 수 있는 것이 없다.
-- ============================================================================
INSERT INTO tb_code (code_group_seq, code_id, code_name, description, attr1, sort_order, created_by)
SELECT g.code_group_seq, 'INBOUND_UNCLOSED', '입고완료 대기',
       '적치가 끝났는데 입고완료를 안 눌렀습니다. 물건은 빈에 있지만 아직 '
    || '재고가 아니라, 주문이 들어오면 결품이 납니다.',
       'amber', 45, 'system'
  FROM tb_code_group g
 WHERE g.code_group_id = 'NOTI_KIND'
   AND NOT EXISTS (SELECT 1 FROM tb_code c
                    WHERE c.code_group_seq = g.code_group_seq
                      AND c.code_id = 'INBOUND_UNCLOSED');
