-- ============================================================================
-- 빈코드를 창고 안에서만 유일하게 바꾼다 (MST-PG-003)
--
-- 재고 1행은 '물류센터 + 창고타입 + 거래처 + 빈 + 제품' 으로 특정된다.
-- 키에 센터와 창고타입이 들어간다는 것은 빈코드만으로는 한 곳이 정해지지
-- 않는다는 뜻이다 — 이천센터에도 김해센터에도 '1A-01-01' 이 있을 수 있다.
--
-- 그런데 지금 제약은 반대로 전역 유일이라, 두 번째 센터가 같은 코드를 쓰지
-- 못한다. 현장은 자기 센터의 랙을 자연스럽게 1A · 1B 로 부르는데, 전역
-- 유일을 강요하면 '이천은 A~M, 김해는 N~Z' 같은 사람이 기억해야 하는 규칙이
-- 생기고 센터가 늘수록 구역 문자가 동난다.
--
-- 창고코드가 이미 '플랜트 안에서만 유일' 이므로 층위도 맞는다.
--
-- 느슨하게 푸는 방향이라 기존 데이터는 하나도 깨지지 않는다.
-- ============================================================================

ALTER TABLE tb_location DROP CONSTRAINT uk_location_id;

ALTER TABLE tb_location
    ADD CONSTRAINT uk_location_wh_id UNIQUE (warehouse_seq, location_id);


