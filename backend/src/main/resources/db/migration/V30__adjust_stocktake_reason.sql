-- ============================================================================
-- 재고조정 사유 '실사 차이' 를 '실사 정정' 으로 (INV-PG-006)
--
-- 이름이 하면 안 되는 일을 부르고 있었다.
--
-- <b>실사 차이는 마감이 이미 반영한다.</b> StocktakeService.close() 가
-- 줄마다 '최종 − 지금 장부' 를 계산해 StockLedger 로 바로 밀어 넣는다.
-- 실사는 조정을 거치지 않는다 — 세고 마감하면 끝이고, 승인 통제도
-- INV_COUNT_APPROVE 로 따로 받는다.
--
-- 그런데 조정 사유에 '실사 차이' 가 있으니 이렇게 읽힌다:
--
--   장부 50, 실물 48
--     실사 마감  →  장부 48   (−2 반영됨)
--     조정 올림  →  장부 46   (−2 또 반영)   ← 같은 차이가 두 번
--
-- 조정 화면은 이것을 막을 수가 없다. '지금 장부 48 을 46 으로' 는 그 자체로
-- 정상 요청이고, 승인자도 사유가 '실사 차이' 라 오히려 자연스럽게 읽는다.
-- <b>틀린 값이 가장 그럴듯해 보이는 모양</b>이다.
--
--
-- 【 그래도 없애지는 않는다 】
--
-- 마감을 잘못했을 때 고치는 길이 조정뿐이다. close() 의 오류 메시지가 그렇게
-- 안내한다 — "마감된 실사는 되돌릴 수 없습니다. 차이를 다시 맞추려면 조정을
-- 올리세요." 그때는 실사가 근거이므로 사유가 필요하다.
--
-- 그래서 코드는 남기고 이름과 설명만 바꾼다.
--
--   '실사 차이'  →  "실사에서 차이가 났으니 올린다" 로 읽힌다
--   '실사 정정'  →  "실사가 잘못됐을 때 바로잡는다" 로 읽힌다
--
-- code_id 는 그대로 둔다. 이미 이 코드로 적힌 조정 전표가 있을 수 있고,
-- 사유 코드를 바꾸면 그 기록이 무엇을 가리켰는지 잃는다.
-- ============================================================================
UPDATE tb_code c
   SET code_name   = '실사 정정',
       description = '실사 마감이 잘못됐을 때 바로잡습니다. 실사 차이 자체는 '
                  || '마감이 이미 장부에 반영했으므로, 그 결과를 여기서 다시 '
                  || '올리면 같은 차이가 두 번 반영됩니다.',
       updated_by  = 'system',
       updated_at  = CURRENT_TIMESTAMP
  FROM tb_code_group g
 WHERE g.code_group_seq = c.code_group_seq
   AND g.code_group_id  = 'REASON_ADJUST'
   AND c.code_id        = 'STOCKTAKE';
