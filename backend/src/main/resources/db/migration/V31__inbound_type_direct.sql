-- ============================================================================
-- 입고 종류에 '직납입고' 를 더한다 (INB-PG-001)
--
-- 거래는 사람 사이에서 일어나고, 시스템의 발주는 그것을 적어 둔 것일 뿐이다.
-- 전화로 정하든 만나서 정하든 약속은 이미 성립했는데, 우리 화면에 전표가
-- 없다고 해서 <b>거래가 없었던 것이 아니다.</b>
--
-- 시즌 물량이 특히 그렇다. 언제 정해졌는지 언제 오는지를 공급처 시스템과
-- 주고받지 못하니, 사람이 듣고 사람이 적는 수밖에 없다. 트럭이 와서야
-- 아는 날도 있다.
--
--
-- 【 막혀 있던 것은 이름 하나였다 】
--
-- 발주 없는 입고는 원래부터 됐다. InboundService 가 PURCHASE 일 때만
-- 발주번호를 찾고, 그 뒤(입하 · 검수 · 적치 · 재고 반영)는 전부 '발주가
-- 있으면' 하는 식으로 짜여 있다.
--
--   if (orderLineSeq == null) return;              예정수량 검사 건너뜀
--   if (inbound.getOrderSeq() != null) refresh…    발주 진행률 갱신 건너뜀
--
-- 그런데 고를 수 있는 이름이 구매 · 반품 · 이동 셋뿐이라, 공급처가 그냥
-- 보낸 물건을 적을 자리가 없었다. 오류 메시지는 이렇게 안내하고 있었다.
--
--   "발주 없이 받는 물건이면 반품입고 · 이동입고로 고르세요"
--
-- <b>틀린 이름을 고르라고 시키는 안내다.</b> 이동입고로 적어 두면 석 달 뒤
-- 그 전표를 본 사람이 "다른 센터에서 왔구나" 하고 읽는다.
--
--
-- 【 이동입고와 섞지 않는 이유 】
--
--   이동입고    우리 안에서 자리만 옮겼다. 정산할 것이 없다
--   직납입고    밖에서 들어왔다. <b>대금이 남아 있다</b>
--
-- 둘을 같은 이름으로 두면 "발주 없이 들어와 아직 정산 근거가 없는 것" 만
-- 뽑아 볼 수가 없다. 하나는 정상 건이고 하나는 미결 건이라, 섞이면 미결이
-- 정상 사이에 숨는다.
--
-- 색을 amber 로 둔 것도 같은 뜻이다. 막지는 않지만 눈에 걸려야 한다.
--
--
-- 【 발주를 나중에 붙이는 것은 막지 않는다 】
--
-- 구매담당이 소급 발주를 내고 이 입고와 잇고 싶을 수 있다. 그 경로는
-- 아직 없지만 tb_inbound.order_seq 가 비어 있을 뿐이라 나중에 채우면
-- 된다 — 지금 길을 막아 두지는 않는다.
-- ============================================================================

INSERT INTO tb_code (code_group_seq, code_id, code_name, description, attr1, sort_order, created_by)
SELECT g.code_group_seq, 'DIRECT', '직납입고',
       '발주 없이 공급처가 직접 보낸 물건. 시즌 물량처럼 사람끼리 정하고 '
    || '오는 건을 적는다. 대금 근거가 아직 없으므로 정산 전에 발주를 '
    || '맞춰야 한다.',
       'amber', 25, 'system'
  FROM tb_code_group g
 WHERE g.code_group_id = 'INBOUND_TYPE'
   AND NOT EXISTS (SELECT 1 FROM tb_code c
                    WHERE c.code_group_seq = g.code_group_seq
                      AND c.code_id = 'DIRECT');

-- 그룹 설명도 사실에 맞춘다
UPDATE tb_code_group
   SET description = '구매입고 · 직납입고 · 반품입고 · 이동입고',
       updated_by  = 'system',
       updated_at  = CURRENT_TIMESTAMP
 WHERE code_group_id = 'INBOUND_TYPE';
