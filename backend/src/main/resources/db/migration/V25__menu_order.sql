-- 사이드바 대분류 순서를 다시 매긴다 (COM-PG-005)
--
-- 두 가지가 문제였다.
--
--   1 순서가 겹쳤다
--     '출고 · 패킹'(V20)과 '권한'(V4)이 둘 다 40 이었다. 같은 값이면
--     순서를 DB 가 정하게 되어, 새로고침마다 위아래가 바뀔 수 있다.
--
--   2 업무 흐름과 거꾸로였다
--     물건은 구매 -> 입고 -> 재고 -> 주문 -> 출고 로 흐르는데, 메뉴는
--     주문(35) -> 출고(40) -> 재고(45) -> 입고(47) -> 구매(50) 였다.
--     처음에 10 단위로 시작해 놓고 업무가 하나씩 늘 때마다 사이에 끼워
--     넣다가 35 · 45 · 47 이 생긴 결과다.
--
-- 다시 매기면서 셋을 지킨다.
--
--   · 업무 메뉴를 흐름대로
--   · 기본 설정(권한 · 공통정책 · 공통코드)은 맨 아래로 — 매일 쓰는 것이
--     아니라 처음 한 번 깔아 두는 것이고, 위에 있으면 업무 메뉴를 밀어낸다
--   · 권한을 공통정책 위에 — 역할과 권한이 정해져야 정책을 걸 대상이 생긴다
--   · 10 단위로 벌려 둔다. 배송 · 반품(6차)이 사이에 들어온다
-- ============================================================================
UPDATE tb_menu SET sort_order = v.ord, updated_by = 'system', updated_at = CURRENT_TIMESTAMP
  FROM (VALUES
        -- 업무
        ('GRP_STATUS',  10),   -- 현황
        ('GRP_MASTER',  20),   -- 기준정보
        ('GRP_PUR',     30),   -- 구매
        ('GRP_INB',     40),   -- 입고
        ('GRP_STOCK',   50),   -- 재고
        ('GRP_ORDER',   60),   -- 주문 · 할당
        ('GRP_OUT',     70),   -- 출고 · 패킹
        -- 관리 · 설정. 처음 한 번 깔아 두는 것들이라 아래에 둔다.
        ('GRP_USER',    80),   -- 사용자 · 조직
        ('GRP_AUTH',    85),   -- 권한      (공통정책 위)
        ('GRP_COMMON',  90),   -- 공통정책 · 공통코드 · 업로드 이력
        ('GRP_AUDIT',   95)    -- 감사
       ) AS v(menu_id, ord)
 WHERE tb_menu.menu_id = v.menu_id;
