-- ============================================================================
-- 입하에 박스 · 파렛트 수를 적을 자리를 만든다 (INB-PG-002)
--
-- 물건은 박스로 온다. 그런데 입하 화면에는 SKU 줄마다 낱개 수량 칸만
-- 있어서, 차에서 내리는 자리에서 셀 수 없는 단위를 적으라고 하고 있었다.
--
-- <b>기사는 기다려 주지 않는다.</b> 20줄짜리 표를 채우려면 차를 세워 두고
-- 박스를 뜯어 세야 하는데, 실제로는 아무도 그렇게 하지 않는다. 그래서
-- 예정수량을 그대로 둔 채 저장하고, 정확한 수량은 검수에서 센다 — 설계가
-- 원래 그렇게 돼 있다(INB-003: 입하수량은 예정수량을 덮지 않는다).
--
-- 그러면 입하가 실제로 남기는 것은 <b>차가 왔다</b>와 <b>누가 가져왔다</b>
-- 두 가지뿐이었다. 거기에 <b>몇 개가 왔다</b>를 더한다 — 낱개가 아니라
-- 그 자리에서 셀 수 있는 단위로.
--
--
-- 【 검수에서 값어치가 난다 】
--
--   3파렛트 받았는데 2파렛트만 검수됐다
--
-- 낱개 수량만으로는 이것이 안 보인다. 한 파렛트가 통째로 마당에 남아
-- 있어도 숫자가 맞으면 아무도 모르고, 며칠 뒤 재고 차이로만 나타난다.
--
--
-- 【 비워 둘 수 있다 】
--
-- 낱개로 오는 입고도 있고, 세지 못하고 받는 날도 있다. 필수로 걸면
-- 적을 수 없을 때 아무 숫자나 넣게 되고, 그러면 있는 것보다 못하다.
-- ============================================================================
ALTER TABLE tb_inbound
    ADD COLUMN box_count    integer,
    ADD COLUMN pallet_count integer;

ALTER TABLE tb_inbound
    ADD CONSTRAINT ck_inbound_box    CHECK (box_count    IS NULL OR box_count    >= 0),
    ADD CONSTRAINT ck_inbound_pallet CHECK (pallet_count IS NULL OR pallet_count >= 0);

COMMENT ON COLUMN tb_inbound.box_count    IS '입하 시 내린 박스 수. 낱개 수량은 검수에서 센다';
COMMENT ON COLUMN tb_inbound.pallet_count IS '입하 시 내린 파렛트 수';
