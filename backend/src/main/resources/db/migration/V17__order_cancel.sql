-- ============================================================================
-- 주문취소 · 주문정보 변경 (3차 · E섹터)
--   ORD-PG-007  주문취소
--   ORD-PG-008  주문정보 변경
--
-- 테이블도 컬럼도 새로 만들지 않는다. V13 이 취소 자리를 이미 뒀다 —
-- canceled_by · canceled_at · cancel_reason 과 '취소면 누가 · 왜 가 있어야
-- 한다' 는 제약(ck_order_canceled)까지. 배송지 변경도 이미 있는 칸을 고치는
-- 일이라 더할 것이 없다.
--
-- 여기서 채우는 것은 코드 하나뿐이다.
-- ============================================================================


-- ----------------------------------------------------------------------------
-- 할당을 푸는 사유에 '주문취소' 를 더한다
--
-- 주문을 취소하면 잡아 둔 재고를 풀어야 한다. 그때 tb_stock_alloc 에
-- release_reason 을 남기는데, 지금 그 자리에 쓸 수 있는 값은 현품 없음 ·
-- 현품 파손 · 위치 오류뿐이다. 셋 다 창고에서 물건을 못 찾았다는 뜻이라,
-- 주문이 취소돼서 푼 것을 그중 하나로 적으면 나중에 '왜 이 재고가 돌아왔나'
-- 에 틀린 답이 남는다.
--
-- 주문의 취소사유(REASON_CANCEL)를 여기 그대로 넣지 않는다. 그 사유는
-- 주문에 이미 적혀 있고, 할당이 알아야 하는 것은 '주문이 취소돼서 풀렸다'
-- 는 사실 하나다 — 고객이 변심했는지 중복 주문이었는지는 주문을 보면 된다.
--
-- 코드그룹 이름도 고친다. 만들 때는 피킹 결품만 생각했는데, 실제로는
-- 할당을 푸는 모든 경우가 이 그룹을 쓴다.
-- ----------------------------------------------------------------------------
UPDATE tb_code_group
   SET code_group_name = '결품 · 할당해제 사유',
       description     = '피킹 결품 (OUT-007) · 할당 해제 (ORD-PG-005, ORD-PG-007)',
       updated_by      = 'system',
       updated_at      = now()
 WHERE code_group_id = 'REASON_SHORT';

INSERT INTO tb_code (code_group_seq, code_id, code_name, description, attr1, sort_order, created_by)
SELECT g.code_group_seq, 'ORDER_CANCEL', '주문취소',
       '주문이 취소되어 잡아 둔 재고를 풀었다', 'red', 40, 'system'
  FROM tb_code_group g
 WHERE g.code_group_id = 'REASON_SHORT';
