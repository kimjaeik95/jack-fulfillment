-- ============================================================================
-- 로그인 잠금을 단계로 나눈다 (COM-PG-001)
--
-- 지금까지는 5회 틀리면 곧바로 영구 잠금이었다. 관리자가 풀어 주기 전까지
-- 아무것도 못 한다.
--
-- 그런데 5회 틀리는 사람 대부분은 공격자가 아니라 <b>캡스록을 켜 둔 사람</b>이다.
-- 그 사람까지 관리자를 찾아가게 만들면, 관리자는 하루에 몇 번씩 같은 일을
-- 하다가 결국 "그냥 풀어 주는 버튼" 을 아무에게나 주게 된다. 통제가 귀찮아지면
-- 통제가 사라진다.
--
-- 그래서 셋으로 나눈다.
--
--    5회   일시잠금  5분     스스로 풀린다
--   10회   장기잠금  1시간   스스로 풀리지만 한 번 쉬어 간다
--   15회   영구잠금  관리자 해제 필요
--
-- 손가락이 미끄러진 사람은 1단계에서 끝나고, 집요하게 두드리는 쪽만 관리자까지
-- 간다. 횟수와 시간은 application.yml 의 app.security.lockout 에서 바꾼다 —
-- 운영에서 조이고 싶을 때 코드를 고치지 않아도 된다.
-- ============================================================================

ALTER TABLE tb_user
    /*
     * 이 시각까지 로그인할 수 없다. NULL 이면 시한 잠금이 없다는 뜻이다.
     *
     * 영구 잠금은 이 컬럼이 아니라 status='LOCKED' 로 남는다. 둘을 나눈 이유는
     * "시간이 지나면 풀리는 것" 과 "사람이 풀어야 하는 것" 이 다른 사실이기
     * 때문이다. 한 컬럼에 담으면 9999년 같은 값을 넣게 되고, 그 값을 나중에
     * 아무도 설명하지 못한다.
     */
    ADD COLUMN locked_until timestamp;

COMMENT ON COLUMN tb_user.locked_until IS
    '이 시각까지 로그인 불가. 시한 잠금 전용이며 영구 잠금은 status=LOCKED (COM-PG-001)';

-- 잠긴 계정을 찾을 때 쓴다. 관리자 화면이 "지금 몇 명이 잠겨 있나" 를 묻는다.
CREATE INDEX ix_user_locked_until ON tb_user (locked_until)
    WHERE locked_until IS NOT NULL;
