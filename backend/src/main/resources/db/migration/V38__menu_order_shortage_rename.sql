-- ============================================================================
-- '결품 관리' → '전사재고 결품관리' — 결품이 두 종류인데 이름이 하나였다
--
-- 사이드바에 결품이 둘 있었다.
--
--   주문 · 할당   결품 관리     재고가 없어 할당을 못 잡았다
--   출고 · 패킹   피킹 결품     전산엔 있는데 빈에 가 보니 없었다
--
-- 앞쪽이 그냥 '결품 관리' 라, 피킹 결품이 그 하위이거나 둘이 같은 것으로
-- 읽혔다. 실제로 한 쪽을 찾다가 다른 쪽을 열어 '왜 안 보이지' 가 됐다.
--
-- 둘은 뒤처리가 전혀 다르다.
--
--   전사재고 결품   발주 · 입고로 푼다.      재고가 없는 것은 사고가 아니다
--   피킹 결품       실사 · 조정으로 푼다.    장부가 틀렸다는 뜻이라 사고다
--
-- '전사재고' 를 붙이면 '어디에도 없다' 가 드러나고, '빈에 없다' 와 자리가
-- 갈린다. 피킹 결품은 그대로 둔다 — 이미 어느 단계의 결품인지 말하고 있다.
--
-- 화면 제목과 라우트 meta.title 도 같이 바꾼다. 메뉴는 DB 가, 제목은 코드가
-- 들고 있어서 한쪽만 고치면 사이드바와 화면 머리글이 다른 말을 한다.
-- ============================================================================

UPDATE tb_menu
   SET menu_name  = '전사재고 결품관리',
       updated_by = 'system',
       updated_at = CURRENT_TIMESTAMP
 WHERE menu_id = 'ORD_SHORTS';
