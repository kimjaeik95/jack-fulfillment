-- ============================================================================
-- 본사 기준정보에서 승인 작업함을 거둔다 (V916 정정)
--
-- V916 이 HQ_MASTER 에게 SYS_APPROVAL 을 주면서 '결재할 것이 있는 역할' 이라
-- 적었는데, 확인해 보니 <b>결재할 것이 하나도 없다.</b> 작업함이 다루는 세
-- 문서(구매요청 · 재고조정 · 입고정정) 중 어느 것도 HQ_MASTER 에게 액션 A 가
-- 없다.
--
--   결재 권한을 가진 역할        무엇을 결재하나
--   PURCHASER                    구매요청
--   CENTER_MGR                   재고조정 · 입고정정
--   SYS_ADMIN                    전부
--
-- 그래서 HQ_MASTER 가 작업함을 열면 세 종류가 모두 '권한 없어 빠짐' 으로
-- 걸러진 빈 화면이 나온다. 늘 비어 있는 메뉴는 쓸모가 없는 정도가 아니라
-- <b>해로운데</b>, 몇 번 열어 보고 비어 있으면 진짜 결재할 것이 생겨도 안
-- 열게 되기 때문이다.
--
-- 본사 기준정보가 실제로 결재하는 것이 생기면 (SKU 폐기 승인 같은 것) 그때
-- 그 권한과 함께 다시 준다.
--
-- 통합검색(SYS_SEARCH)은 그대로 둔다. 기준정보를 만드는 사람이 그 SKU 가
-- 어디로 갔나를 보는 것은 자연스럽다.
-- ============================================================================
DELETE FROM tb_role_permission rp
 USING tb_role r, tb_permission p
 WHERE r.role_seq = rp.role_seq
   AND p.perm_seq = rp.perm_seq
   AND r.role_id  = 'HQ_MASTER'
   AND p.perm_id  = 'SYS_APPROVAL';
